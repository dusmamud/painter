// Regenerates src/components/Icon.astro from the canonical Lucide SVG
// files (lucide-static, MIT). Every icon stays on the 24x24 grid with a
// 2px stroke and round caps/joins — the whole set comes from one source,
// so stroke weight and corner style can never drift apart.
//
// Site names are kept stable (pin, arrow, roller...) so call sites never
// change when the underlying Lucide icon is renamed (house, map-pin...).
// The star is the one deliberate exception: ratings render it filled,
// so its path carries fill="currentColor" stroke="none".
//
// Run: node scripts/extract-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const iconsDir = join(root, 'node_modules/lucide-static/icons');

// site name -> lucide file stem
const MAP = {
  'arrow-left': 'arrow-left',
  'arrow-up': 'arrow-up',
  arrow: 'arrow-right',
  'badge-check': 'badge-check',
  building: 'building-2',
  brush: 'paintbrush',
  calculator: 'calculator',
  calendar: 'calendar',
  chat: 'message-circle',
  check: 'check',
  chevron: 'chevron-down',
  'chevrons-left-right': 'chevrons-left-right',
  'circle-dashed': 'circle-dashed',
  clock: 'clock',
  droplet: 'droplet',
  droplets: 'droplets',
  egg: 'egg',
  eye: 'eye',
  feather: 'feather',
  heart: 'heart',
  home: 'house',
  layers: 'layers',
  leaf: 'leaf',
  mail: 'mail',
  menu: 'menu',
  palette: 'palette',
  'paint-bucket': 'paint-bucket',
  phone: 'phone',
  pin: 'map-pin',
  play: 'circle-play',
  plus: 'plus',
  'pencil-ruler': 'pencil-ruler',
  quote: 'quote',
  roller: 'paint-roller',
  ruler: 'ruler',
  shield: 'shield-check',
  smile: 'smile',
  sparkles: 'sparkles',
  'spray-can': 'spray-can',
  star: 'star',
  sun: 'sun',
  tag: 'tag',
  timer: 'timer',
  trophy: 'trophy',
  users: 'users',
  wallet: 'wallet',
  x: 'x',
};

const inner = (stem) => {
  const svg = readFileSync(join(iconsDir, `${stem}.svg`), 'utf8');
  const m = svg.match(/<svg[^>]*>([\s\S]*?)<\/svg>/);
  if (!m) throw new Error(`no inner content in ${stem}.svg`);
  return m[1].replace(/\s+/g, ' ').trim();
};

const entries = Object.entries(MAP).map(([name, stem]) => {
  let body = inner(stem);
  if (name === 'star') {
    // Ratings render filled stars: force fill on the (single) shape.
    body = body.replace(/<(path|polygon|circle|rect)/, '<$1 fill="currentColor" stroke="none"');
  }
  if (body.includes("'")) throw new Error(`single quote in ${stem}`);
  return `  '${name}': '${body}',`;
});

const out = `---
/**
 * Icon set: genuine Lucide path data (lucide-static, MIT), generated by
 * scripts/extract-icons.mjs — do not hand-edit the paths. 24x24 grid,
 * 2px stroke, round caps/joins, currentColor. Re-run the script after
 * changing the icon list or upgrading lucide-static.
 */
const paths: Record<string, string> = {
${entries.join('\n')}
};

interface Props {
  name: keyof typeof paths;
  class?: string;
}

const { name, class: cls } = Astro.props;
---

<svg
  viewBox="0 0 24 24"
  fill="none"
  stroke="currentColor"
  stroke-width="2"
  stroke-linecap="round"
  stroke-linejoin="round"
  class={cls}
  aria-hidden="true"
  set:html={paths[name]}
/>
`;

writeFileSync(join(root, 'src/components/Icon.astro'), out);
console.log(`wrote Icon.astro with ${entries.length} icons`);
